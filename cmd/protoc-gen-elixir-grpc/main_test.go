func testGenerate(t *testing.T, req *pluginpb.CodeGeneratorRequest) *pluginpb.CodeGeneratorResponse {
	t.Helper()

	inputBytes, err := proto.Marshal(req)
	require.NoError(t, err)

	stdout, stderr, exitCode := testRunProtocGenElixirGrpc(t, bytes.NewReader(inputBytes))
	if exitCode != 0 {
		t.Errorf("Plugin failed with exit code %d, stderr: %s", exitCode, stderr.String())
		return nil
	}
	assert.Equal(t, 0, exitCode)
	assert.Equal(t, "", stderr.String())
	assert.Greater(t, len(stdout.Bytes()), 0)

	var output pluginpb.CodeGeneratorResponse
	assert.NoError(t, proto.Unmarshal(stdout.Bytes(), &output))
	return &output
}

func testRunProtocGenElixirGrpc(t *testing.T, stdin io.Reader, args ...string) (stdout, stderr *bytes.Buffer, exitCode int) {
	t.Helper()

	stdout = &bytes.Buffer{}
	stderr = &bytes.Buffer{}
	args = append([]string{"run", "main.go"}, args...)

	cmd := exec.Command("go", args...)
	cmd.Env = os.Environ()
	cmd.Stdin = stdin
	cmd.Stdout = stdout
	cmd.Stderr = stderr
	_ = cmd.Run() // Don't use require.NoError since we want to capture exit codes
	exitCode = cmd.ProcessState.ExitCode()
	return stdout, stderr, exitCode
}

