func TestParseKeyValuePairs(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected map[string]string
	}{
		{
			name:     "empty string",
			input:    "",
			expected: map[string]string{},
		},
		{
			name:     "single key-value",
			input:    "key1=value1",
			expected: map[string]string{"key1": "value1"},
		},
		{
			name:     "single key-value with trailing comma",
			input:    "key1=value1,",
			expected: map[string]string{"key1": "value1"},
		},
		{
			name:     "multiple key-values",
			input:    "key1=value1,key2=value2",
			expected: map[string]string{"key1": "value1", "key2": "value2"},
		},
		{
			name:     "multiple key-values with trailing comma",
			input:    "key1=value1,key2=value2,",
			expected: map[string]string{"key1": "value1", "key2": "value2"},
		},
		{
			name:     "value with commas (codecs)",
			input:    "codecs=A,B,C",
			expected: map[string]string{"codecs": "A,B,C"},
		},
		{
			name:     "value with commas and trailing comma",
			input:    "codecs=A,B,C,",
			expected: map[string]string{"codecs": "A,B,C"},
		},
		{
			name:     "mixed: regular key and value with commas",
			input:    "key1=value1,codecs=A,B,C",
			expected: map[string]string{"key1": "value1", "codecs": "A,B,C"},
		},
		{
			name:     "mixed with trailing comma",
			input:    "key1=value1,codecs=A,B,C,",
			expected: map[string]string{"key1": "value1", "codecs": "A,B,C"},
		},
		{
			name:     "with spaces",
			input:    "key1 = value1 , key2 = value2",
			expected: map[string]string{"key1": "value1", "key2": "value2"},
		},
		{
			name:     "multiple trailing commas",
			input:    "key1=value1,,,",
			expected: map[string]string{"key1": "value1"},
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			result := parseKeyValuePairs(test.input)
			assert.Equal(t, test.expected, result)
		})
	}
}

