// oneofTypeName builds the Pony type alias name for a real oneof.
// e.g. className="Zoo", oneof="kind" → "ZooKind"
func oneofTypeName(className string, oo *protogen.Oneof) string {
	return className + snakeToPascal(string(oo.Desc.Name()))
}

// oneofCaseName builds the Pony wrapper class name for one oneof member.
// e.g. className="Zoo", oneof="kind", field="type_a" → "ZooKindTypeA"
func oneofCaseName(className string, oo *protogen.Oneof, field *protogen.Field) string {
	return className + snakeToPascal(string(oo.Desc.Name())) + snakeToPascal(string(field.Desc.Name()))
}

// snakeToPascal converts snake_case to PascalCase: "type_a" → "TypeA".
func snakeToPascal(s string) string {
	parts := strings.Split(s, "_")
	var b strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			b.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return b.String()
}

func (ctx *genCtx) emitEnum(enum *protogen.Enum, namePrefix string) {
	enumTypeName := namePrefix + string(enum.Desc.Name())
	fromValueName := enumTypeName + "FromValue"
	rawName := enumTypeName + "Raw"

	primNames := make([]string, 0, len(enum.Values))
	for _, v := range enum.Values {
		prim := namePrefix + screamingToPascal(string(v.Desc.Name()))
		ctx.g.P(`primitive `, prim, `   fun value(): I32 => `, v.Desc.Number())
		primNames = append(primNames, prim)
	}

	// Raw class preserves unknown numeric values across decode/re-encode (proto3
	// forward-compat: a peer may send values not yet in this schema).
	ctx.g.P()
	ctx.g.P(`class val `, rawName)
	ctx.g.P(`  let _v: I32`)
	ctx.g.P(`  new val create(v: I32) => _v = v`)
	ctx.g.P(`  fun value(): I32 => _v`)

	ctx.g.P()
	ctx.g.P(`type `, enumTypeName, ` is (`, strings.Join(append(primNames, rawName), " | "), `)`)
	ctx.g.P()
	ctx.g.P(`primitive `, fromValueName)
	ctx.g.P(`  fun apply(v: I32): `, enumTypeName, ` =>`)
	ctx.g.P(`    match v`)
	for _, v := range enum.Values {
		prim := namePrefix + screamingToPascal(string(v.Desc.Name()))
		ctx.g.P(`    | `, v.Desc.Number(), ` => `, prim)
	}
	ctx.g.P(`    else `, rawName, `(v)`)
	ctx.g.P(`    end`)
	ctx.g.P()
}

// isSupported returns true for field shapes we generate code for.
// Out: real oneofs, groups, WKT message/enum refs, map<K, message> (no zero value).
// In: scalars (singular + repeated), messages (singular + repeated, any dir),
// enums (singular + repeated, any dir), proto3 optional, map<K, scalar|enum>.
func (ctx *genCtx) isSupported(field *protogen.Field) bool {
	if field.Desc.IsMap() {
		return ctx.isSupportedMapField(field)
	}
	if field.Oneof != nil && !field.Desc.HasOptionalKeyword() {
		return false
	}
	return ctx.isSupportedOneofMember(field)
}

// wktBlocklist holds the google/protobuf/ files that can't be generated as
// plain proto3 messages: struct.proto has a circular Value↔ListValue↔Struct
// oneof, type.proto and api.proto depend on it, and descriptor.proto is
// descriptor-only. Everything else (Timestamp, Duration, Any, wrappers, etc.)
// generates naturally as regular proto3 messages.
var wktBlocklist = map[string]bool{
	"google/protobuf/struct.proto":     true,
	"google/protobuf/type.proto":       true,
	"google/protobuf/api.proto":        true,
	"google/protobuf/descriptor.proto": true,
}

func isWKT(f protoreflect.FileDescriptor) bool {
	return wktBlocklist[f.Path()]
}

func (ctx *genCtx) fileHasMaps() bool {
	var check func([]*protogen.Message) bool
	check = func(msgs []*protogen.Message) bool {
		for _, msg := range msgs {
			if msg.Desc.IsMapEntry() {
				continue
			}
			for _, f := range msg.Fields {
				if f.Desc.IsMap() && ctx.isSupported(f) {
					return true
				}
			}
			if check(msg.Messages) {
				return true
			}
		}
		return false
	}
	return check(ctx.file.Messages)
}

// crossDirUseDirectives returns sorted relative-path strings for Pony `use`
// directives needed to reference types from other proto packages. Same-
// directory refs are already in the same Pony package and need no import.
func (ctx *genCtx) crossDirUseDirectives() []string {
	thisDir := path.Dir(ctx.file.Desc.Path())
	dirToRel := make(map[string]string)

	addDepPath := func(depPath string) {
		if depPath == "" {
			return
		}
		depDir := path.Dir(depPath)
		if depDir == thisDir {
			return
		}
		if _, ok := dirToRel[depDir]; !ok {
			dirToRel[depDir] = protoRelDir(thisDir, depDir)
		}
	}

	checkField := func(f *protogen.Field) {
		if f.Desc.IsMap() {
			// Map entry message is always co-located; check value for cross-dir deps.
			if f.Message != nil && len(f.Message.Fields) == 2 {
				valField := f.Message.Fields[1]
				switch valField.Desc.Kind() {
				case protoreflect.MessageKind:
					if valField.Message != nil {
						addDepPath(valField.Message.Desc.ParentFile().Path())
					}
				case protoreflect.EnumKind:
					if valField.Enum != nil {
						addDepPath(valField.Enum.Desc.ParentFile().Path())
					}
				}
			}
			return
		}
		switch f.Desc.Kind() {
		case protoreflect.MessageKind:
			if f.Message != nil {
				addDepPath(f.Message.Desc.ParentFile().Path())
			}
		case protoreflect.EnumKind:
			if f.Enum != nil {
				addDepPath(f.Enum.Desc.ParentFile().Path())
			}
		}
	}

	var walkMessages func([]*protogen.Message)
	walkMessages = func(msgs []*protogen.Message) {
		for _, msg := range msgs {
			if msg.Desc.IsMapEntry() {
				continue
			}
			// Collect cross-dir deps from regular supported fields.
			for _, f := range msg.Fields {
				if ctx.isSupported(f) {
					checkField(f)
				}
			}
			// Also collect from oneof members in supported real oneofs.
			for _, oo := range ctx.supportedRealOneofs(msg) {
				for _, f := range oo.Fields {
					checkField(f)
				}
			}
			walkMessages(msg.Messages)
		}
	}
	walkMessages(ctx.file.Messages)

	result := make([]string, 0, len(dirToRel))
	for _, rel := range dirToRel {
		result = append(result, rel)
	}
	sort.Strings(result)
	return result
}

// protoRelDir returns the relative path from fromDir to toDir using
// slash-separated proto path components (e.g. "geo" → "../common").
// If the result doesn't start with "..", it is prefixed with "./" to
// distinguish it from a package-name lookup.
func protoRelDir(fromDir, toDir string) string {
	from := strings.Split(path.Clean(fromDir), "/")
	to := strings.Split(path.Clean(toDir), "/")
	// trim common prefix
	i := 0
	for i < len(from) && i < len(to) && from[i] == to[i] {
		i++
	}
	var parts []string
	for range from[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, to[i:]...)
	rel := strings.Join(parts, "/")
	if !strings.HasPrefix(rel, "..") {
		rel = "./" + rel
	}
	return rel
}

func (ctx *genCtx) supportedFields(fields []*protogen.Field) []*protogen.Field {
	var out []*protogen.Field
	for _, f := range fields {
		if ctx.isSupported(f) {
			out = append(out, f)
		}
	}
	return out
}

// fieldPonyType returns the Pony type declaration for a field.
// Map fields become Map[K, V] val. Repeated fields become Array[elem] val.
// Singular message fields become (ChildMsg val | None).
// Singular enum fields become the enum type alias. Scalars use scalarSpecs.
func (ctx *genCtx) fieldPonyType(field *protogen.Field) string {
	if field.Desc.IsMap() {
		kType := ctx.mapKeyPonyType(field.Message.Fields[0])
		vType := ctx.elemPonyType(field.Message.Fields[1])
		return "Map[" + kType + ", " + vType + "] val"
	}
	if field.Desc.IsList() {
		return "Array[" + ctx.elemPonyType(field) + "] val"
	}
	switch field.Desc.Kind() {
	case protoreflect.MessageKind:
		return "(" + ponyMessageClassName(field.Message) + " val | None)"
	case protoreflect.EnumKind:
		if field.Desc.HasOptionalKeyword() {
			return "(" + ponyEnumTypeName(field.Enum) + " | None)"
		}
		return ponyEnumTypeName(field.Enum)
	}
	if field.Desc.HasOptionalKeyword() {
		return "(" + scalarSpecs[field.Desc.Kind()].ponyType + " | None)"
	}
	return scalarSpecs[field.Desc.Kind()].ponyType
}

// elemPonyType returns the element type for repeated fields (no None wrapper
// for messages — each element is always present).
func (ctx *genCtx) elemPonyType(field *protogen.Field) string {
	switch field.Desc.Kind() {
	case protoreflect.MessageKind:
		return ponyMessageClassName(field.Message) + " val"
	case protoreflect.EnumKind:
		return ponyEnumTypeName(field.Enum)
	}
	return scalarSpecs[field.Desc.Kind()].ponyType
}

// fieldPonyDefault returns the default value expression for a field.
func (ctx *genCtx) fieldPonyDefault(field *protogen.Field) string {
	if field.Desc.IsMap() {
		kType := ctx.mapKeyPonyType(field.Message.Fields[0])
		vType := ctx.elemPonyType(field.Message.Fields[1])
		return "recover val Map[" + kType + ", " + vType + "] end"
	}
	if field.Desc.IsList() {
		return "recover val Array[" + ctx.elemPonyType(field) + "] end"
	}
	switch field.Desc.Kind() {
	case protoreflect.MessageKind:
		return "None"
	case protoreflect.EnumKind:
		if field.Desc.HasOptionalKeyword() {
			return "None"
		}
		return ponyEnumZeroValuePrimitive(field.Enum)
	}
	if field.Desc.HasOptionalKeyword() {
		return "None"
	}
	return scalarSpecs[field.Desc.Kind()].ponyDefault
}

// ── Name helpers ─────────────────────────────────────────────────────────────

// screamingToPascal converts SCREAMING_SNAKE_CASE to PascalCase.
// STATUS_UNKNOWN → StatusUnknown, ACTIVE → Active.
func screamingToPascal(s string) string {
	return snakeToPascal(strings.ToLower(s))
}

// ponyMessageClassName builds the flat Pony class name for a message by
// walking the parent chain (Outer.Inner → Outer_Inner).
func ponyMessageClassName(msg *protogen.Message) string {
	var ancestors []string
	parent := msg.Desc.Parent()
	for {
		parentMsg, ok := parent.(protoreflect.MessageDescriptor)
		if !ok {
			break
		}
		ancestors = append(ancestors, string(parentMsg.Name()))
		parent = parentMsg.Parent()
	}
	// ancestors are innermost-first; reverse to outermost-first
	for i, j := 0, len(ancestors)-1; i < j; i, j = i+1, j-1 {
		ancestors[i], ancestors[j] = ancestors[j], ancestors[i]
	}
	return strings.Join(append(ancestors, string(msg.Desc.Name())), "_")
}

// enumNamePrefix returns the message-hierarchy prefix (e.g. "Zoo_") for
// an enum nested inside messages. Top-level enums return "".
func enumNamePrefix(enum *protogen.Enum) string {
	var ancestors []string
	parent := enum.Desc.Parent()
	for {
		parentMsg, ok := parent.(protoreflect.MessageDescriptor)
		if !ok {
			break
		}
		ancestors = append(ancestors, string(parentMsg.Name()))
		parent = parentMsg.Parent()
	}
	if len(ancestors) == 0 {
		return ""
	}
	for i, j := 0, len(ancestors)-1; i < j; i, j = i+1, j-1 {
		ancestors[i], ancestors[j] = ancestors[j], ancestors[i]
	}
	return strings.Join(ancestors, "_") + "_"
}

// ponyEnumTypeName returns the Pony type alias name for an enum.
func ponyEnumTypeName(enum *protogen.Enum) string {
	return enumNamePrefix(enum) + string(enum.Desc.Name())
}

func ponyEnumFromValueName(enum *protogen.Enum) string {
	return ponyEnumTypeName(enum) + "FromValue"
}

// ponyEnumZeroValuePrimitive returns the Pony primitive name for the proto3
// zero value (number == 0) of an enum.
func ponyEnumZeroValuePrimitive(enum *protogen.Enum) string {
	prefix := enumNamePrefix(enum)
	for _, v := range enum.Values {
		if v.Desc.Number() == 0 {
			return prefix + screamingToPascal(string(v.Desc.Name()))
		}
	}
	if len(enum.Values) > 0 {
		return prefix + screamingToPascal(string(enum.Values[0].Desc.Name()))
	}
	return ponyEnumTypeName(enum) + "Zero"
}

// ── fieldShape ────────────────────────────────────────────────────────────────

// fieldShape returns a short string describing why a field is unsupported,
// for the TODO comment.
func fieldShape(field *protogen.Field) string {
	var parts []string
	if field.Desc.IsMap() {
		parts = append(parts, "map")
	} else if field.Desc.IsList() {
		parts = append(parts, "repeated")
	}
	if field.Desc.HasOptionalKeyword() {
		parts = append(parts, "optional")
	}
	if field.Oneof != nil {
		parts = append(parts, "oneof")
	}
	parts = append(parts, field.Desc.Kind().String())
	return strings.Join(parts, " ")
}

